def export_brand_optimization_report(
    report_markdown: str,
    brand: str = "IKEA",
    output_dir: Optional[str] = None,
    with_timestamp: bool = False,
) -> Dict[str, str]:
    """
    Exports the generated brand search optimization report to Markdown and HTML.

    Args:
        report_markdown: The markdown content generated by the agents.
        brand: The brand name analyzed (default 'IKEA').
        output_dir: Target directory (default: 'reports/').
        with_timestamp: Whether to append a timestamp to the filename (default False).

    Returns:
        Dictionary with paths to the exported .md and .html files.
    """
    if output_dir is None:
        project_root = Path(__file__).resolve().parent.parent.parent
        target_dir = project_root / "reports"
    else:
        target_dir = Path(output_dir)

    target_dir.mkdir(parents=True, exist_ok=True)

    brand_slug = brand.lower().replace(" ", "_")
    
    if with_timestamp:
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        md_filename = target_dir / f"{brand_slug}_brand_optimization_report_{timestamp}.md"
        html_filename = target_dir / f"{brand_slug}_brand_optimization_report_{timestamp}.html"
    else:
        md_filename = target_dir / f"{brand_slug}_brand_optimization_report.md"
        html_filename = target_dir / f"{brand_slug}_brand_optimization_report.html"

    # Write single clean Markdown file
    with open(md_filename, "w", encoding="utf-8") as f:
        f.write(report_markdown)

    # Write single clean HTML file
    html_content = generate_html_report(report_markdown, brand=brand)
    with open(html_filename, "w", encoding="utf-8") as f:
        f.write(html_content)

    print(f"📄 [Report Exporter] Saved Markdown report to: {md_filename}")
    print(f"🌐 [Report Exporter] Saved HTML report to: {html_filename}")

    return {
        "markdown_path": str(md_filename),
        "html_path": str(html_filename),
    }
